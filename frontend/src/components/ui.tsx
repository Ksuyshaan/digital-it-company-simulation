export function Avatar({ user, size = 32, dark }: { user?: Pick<User, 'name' | 'photo' | 'role'> | null; size?: number; dark?: boolean }) {
  if (!user) return <span className="avatar" style={{ width: size, height: size }}>–</span>
  const staff = user.role === 'teacher' || user.role === 'assistant'
  const cls = `avatar ${dark || staff ? 'avatar-dark' : ''} ${user.role === 'admin' ? 'avatar-orange' : ''}`
  if (user.photo) return <img className="avatar" src={user.photo} alt="" style={{ width: size, height: size }} />
  return (
    <span className={cls} style={{ width: size, height: size, fontSize: Math.max(10, size * 0.34) }}>
      {staff && user.role === 'teacher' && size < 40 ? 'ПР' : initials(user.name)}
    </span>
  )
}

export function Modal({ title, onClose, children, wide, footer }: { title: ReactNode; onClose: () => void; children: ReactNode; wide?: boolean; footer?: ReactNode }) {
  useEffect(() => {
    const k = (e: KeyboardEvent) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', k)
    document.body.classList.add('modal-open')
    return () => {
      window.removeEventListener('keydown', k)
      document.body.classList.remove('modal-open')
    }
  }, [onClose])
  return (
    <div className="modal-back" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className={`modal ${wide ? 'modal-wide' : ''}`} role="dialog" aria-modal>
        <div className="modal-head">
          <h3>{title}</h3>
          <button className="icon-btn" onClick={onClose} aria-label="Закрыть">
            <Icon name="x" />
          </button>
        </div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>
  )
}


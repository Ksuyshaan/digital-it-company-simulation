export function Toggle({ on, onChange, label }: { on: boolean; onChange: (v: boolean) => void; label?: ReactNode }) {
  return (
    <button type="button" className={`toggle ${on ? 'on' : ''}`} onClick={() => onChange(!on)} aria-pressed={on}>
      <span className="toggle-knob" />
      {label && <span className="toggle-label">{label}</span>}
    </button>
  )
}

/** Выбор файлов: возвращает метаданные (в демо файлы не загружаются на сервер) */
export function FilePick({ onFiles, children, accept, multiple = true }: { onFiles: (f: File[]) => void; children: ReactNode; accept?: string; multiple?: boolean }) {
  return (
    <label className="file-pick">
      {children}
      <input
        type="file"
        multiple={multiple}
        accept={accept}
        onChange={(e) => {
          const files: File[] = Array.from((e.target as HTMLInputElement).files ?? [])
          e.target.value = ''
          if (files.length) onFiles(files)
        }}
      />
    </label>
  )
}

export function Bar({ value, max, color = 'var(--green)' }: { value: number; max: number; color?: string }) {
  return (
    <div className="bar">
      <div style={{ width: `${Math.min(100, (100 * value) / Math.max(1, max))}%`, background: color }} />
    </div>
  )
}

export function Highlight({ text }: { text: string }) {
  const parts = text.split(/(@[A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]+)/g)
  return (
    <>
      {parts.map((p, i) =>
        p.startsWith('@') ? (
          <span key={i} className="mention">
            {p}
          </span>
        ) : (
          p
        ),
      )}
    </>
  )
}
